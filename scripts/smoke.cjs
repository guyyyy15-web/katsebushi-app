// Phone test: iPhone viewport, the real files over a local server. Screenshots in screenshots/.
const { chromium, devices } = require('playwright')
const http = require('http')
const fs = require('fs')
const path = require('path')
const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.png': 'image/png', '.webmanifest': 'application/manifest+json', '.svg': 'image/svg+xml', '.json': 'application/json' }
const root = path.join(__dirname, '..')
const server = http.createServer((req, res) => {
  const f = path.join(root, decodeURIComponent(req.url.split('?')[0]).replace(/\/$/, '/index.html'))
  if (!f.startsWith(root) || !fs.existsSync(f)) { res.writeHead(404); return res.end() }
  res.writeHead(200, { 'Content-Type': TYPES[path.extname(f)] || 'application/octet-stream' })
  fs.createReadStream(f).pipe(res)
})
let fails = 0
const ok = (c, m) => { console.log(`${c ? 'ok ' : 'FAIL'} ${m}`); if (!c) fails++ }

;(async () => {
  await new Promise((r) => server.listen(8765, r))
  const URL = 'http://localhost:8765/'
  const shots = path.join(root, 'screenshots')
  fs.mkdirSync(shots, { recursive: true })
  const b = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] }) // WebGL for the 3D dice
  const ctx = await b.newContext({ ...devices['iPhone 13'], acceptDownloads: true })
  const p = await ctx.newPage()
  const errs = []
  p.on('pageerror', (e) => errs.push(e.message))
  await p.goto(URL)
  await p.waitForSelector('text=My Turn')
  ok(await p.isVisible('text=No backup yet'), 'home asks for a first backup')
  ok(await p.isVisible('text=Add to your Home Screen'), 'iPhone in Safari: the add-to-home-screen card shows')
  await p.screenshot({ path: `${shots}/01-home.png` })

  // Long rest really resets everything (it used to keep only the last of three updates).
  for (let i = 0; i < 5; i++) await p.click('button:has-text("−")')
  await p.click('text=Short / Long Rest')
  await p.click('text=Take a Long Rest')
  await p.waitForSelector('text=Long rest: HP')
  ok(await p.isVisible('text=41/41'), 'a long rest restores HP (was a bug)')
  await p.click('button:has-text("←")')

  // The 🎲 tray, from any screen: pick dice, throw them on screen, the total is read from the dice.
  await p.click('text=Level Timeline')
  await p.click('button[aria-label="Dice"]')
  await p.click('button[aria-label="Add a d6"]')
  await p.click('button[aria-label="Add a d6"]')
  await p.click('button[aria-label="Bonus up"]')
  ok(await p.isVisible('button:has-text("Throw d20 + 2d6 + 1")'), 'the tray builds "d20 + 2d6 + 1"')
  // − takes one die off, Reset clears everything, then build it again
  await p.click('button[aria-label="Remove a d6"]')
  ok(await p.isVisible('button:has-text("Throw d20 + d6 + 1")'), '− takes one d6 off')
  await p.click('button[aria-label="Reset all dice and the bonus"]')
  ok(await p.isVisible('text=Tap the dice to throw') && await p.isDisabled('button[aria-label="Remove a d20"]'), 'Reset clears every die and the bonus')
  await p.click('button[aria-label="Add a d20"]')
  await p.click('button[aria-label="Add a d6"]')
  await p.click('button[aria-label="Add a d6"]')
  await p.click('button[aria-label="Bonus up"]')
  await p.screenshot({ path: `${shots}/04-tray.png` })
  await p.click('button:has-text("Throw d20 + 2d6 + 1")')
  await p.waitForSelector('.dice3d canvas', { timeout: 15000 })
  await p.waitForTimeout(500)
  await p.screenshot({ path: `${shots}/05-throw.png` })
  await p.waitForFunction(() => /Tap to close/.test(document.querySelector('.dice3d')?.textContent || ''), null, { timeout: 20000 })
  await p.screenshot({ path: `${shots}/06-landed.png` })
  const shown = await p.evaluate(() => document.querySelector('.dice3d').innerText)
  const m = /\n(\d+)\n(d20\[(\d+)\] d6\[(\d+), (\d+)\] \+1)/.exec(shown)
  ok(m && Number(m[1]) === Number(m[3]) + Number(m[4]) + Number(m[5]) + 1, `3D throw: the total adds up the faces that landed (${shown.replace(/\s+/g, ' ').trim()})`)
  await p.click('.dice3d')
  ok(await p.isVisible('text=Level Timeline'), 'closing the throw goes back to the same screen')

  // The Dice screen (instant numbers here, so the checks are quick)
  await p.click('button:has-text("←")')
  await p.click('text=Dice')
  await p.click('button:has-text("Throw on screen")')
  await p.click('button:text-is("Advantage")')
  await p.click('button:has-text("Unarmed to hit")')
  const big = await p.textContent('[aria-live="polite"]')
  ok(/Unarmed Strike/.test(big) && /keep/.test(big) && /\+6/.test(big), `advantage roll shows both dice and the +6 bonus (${big.replace(/\s+/g, ' ').trim()})`)
  await p.click('button:has-text("WIS")')
  await p.click('button:has-text("Unarmed damage")')
  ok(await p.isVisible('text=Earlier'), 'earlier rolls are listed')
  await p.screenshot({ path: `${shots}/02-dice.png`, fullPage: true })
  await p.click('button:has-text("←")')

  // Export, then import into a fresh browser
  await p.click('text=Save States')
  const [dl] = await Promise.all([p.waitForEvent('download'), p.click('text=Export all')])
  const file = path.join(shots, dl.suggestedFilename())
  await dl.saveAs(file)
  ok(/^katsebushi-\d{4}-\d{2}-\d{2}\.json$/.test(dl.suggestedFilename()), `export downloads ${dl.suggestedFilename()}`)
  await p.waitForSelector('text=Backup saved')
  await p.screenshot({ path: `${shots}/03-saves.png` })
  const ctx2 = await b.newContext({ ...devices['iPhone 13'] })
  const q = await ctx2.newPage()
  q.on('pageerror', (e) => errs.push(e.message))
  await q.goto(URL)
  await q.click('text=Save States')
  await q.setInputFiles('input[type=file]', file)
  await q.waitForSelector('text=Imported 1 save state')
  ok(await q.isVisible('text=(imported)'), 'a new phone imports the backup as a save state')
  await q.setInputFiles('input[type=file]', { name: 'x.json', mimeType: 'application/json', buffer: Buffer.from('hello') })
  ok(await q.waitForSelector("text=isn't a Katsebushi backup").then(() => true), 'a wrong file is refused politely')

  // Offline: the service worker serves the app.
  await p.goto(URL)
  await p.evaluate(() => navigator.serviceWorker.ready)
  await p.reload()
  await p.waitForSelector('text=My Turn')
  await ctx.setOffline(true)
  await p.reload()
  ok(await p.waitForSelector('text=My Turn', { timeout: 8000 }).then(() => true).catch(() => false), 'opens with no network (service worker)')
  ok(!(await p.isVisible('text=No backup yet')), 'after exporting, the backup reminder is gone')
  ok(await p.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), 'no sideways scroll')
  ok(!errs.length, `no page errors ${errs.join(' | ')}`)
  await b.close()
  server.close()
  console.log(fails ? `\n${fails} failed` : '\nall good')
  process.exit(fails ? 1 : 0)
})()
